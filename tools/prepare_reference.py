"""Copy only selected data/images and literal metadata from the supplied ZIP.

This script does not import the original code or load its serialized models.
"""

import ast
import argparse
import hashlib
import json
from pathlib import Path
from zipfile import ZipFile

ROOT = Path(__file__).resolve().parents[1]


def main(source):
    for folder in ("data", "samples", "models", "reports", "notebooks", "src", "tests", ".vscode"):
        (ROOT / folder).mkdir(parents=True, exist_ok=True)
    paths = [
        "data/crop_recommendation.csv",
        "data/fertilizer_data.csv",
        "data/crop_yield_data.csv",
        "samples/healthy_leaf.png",
        "samples/tomato_early_blight.png",
        "samples/potato_late_blight.png",
        "samples/corn_rust.png",
        "samples/rice_blast.png",
    ]
    hashes = {}
    with ZipFile(source) as archive:
        for name in paths:
            data = archive.read("agri-ai-suite/" + name)
            (ROOT / name).write_bytes(data)
            hashes[name] = hashlib.sha256(data).hexdigest()
        tree = ast.parse(archive.read("agri-ai-suite/src/utils.py").decode("utf-8-sig"))
        metadata = {}
        for node in tree.body:
            if isinstance(node, ast.Assign):
                for target in node.targets:
                    if isinstance(target, ast.Name) and target.id in {"CROP_METADATA", "FERTILIZER_GUIDE"}:
                        metadata[target.id] = ast.literal_eval(node.value)
        for crop in metadata["CROP_METADATA"].values():
            crop.pop("msp_per_quintal", None)
        (ROOT / "data/reference_metadata.json").write_text(
            json.dumps(metadata, indent=2, ensure_ascii=False), encoding="utf-8"
        )
    provenance = {
        "source": source.name,
        "archive_sha256": hashlib.sha256(source.read_bytes()).hexdigest(),
        "files_sha256": hashes,
        "data_type": "Synthetic educational records; source contains data/generate_datasets.py.",
        "images": "Illustrations generated by the reference project's sample-generation code.",
        "metadata": "Illustrative text copied from reference; not independently verified agronomic advice.",
        "units": "N/P/K scales are undocumented and differ between datasets. Crop rainfall period is undocumented.",
        "license": "No license file found in the supplied archive. Preserve attribution; confirm rights before public redistribution.",
    }
    (ROOT / "data/provenance.json").write_text(json.dumps(provenance, indent=2), encoding="utf-8")
    print("Prepared three datasets, five sample images, reference metadata and provenance.")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("archive", type=Path, help="Path to the user-supplied agri-ai-suite.zip")
    main(parser.parse_args().archive)
